fit_binary_qc_model <- function(poly, threshold = c("above_LOQ", "at_or_above_LOD")) {
  threshold <- match.arg(threshold)
  qcol <- paste0("QC_flag_", poly)
  d <- cohort |>
    mutate(
      exposure = case_when(
        threshold == "above_LOQ" ~ as.integer(.data[[qcol]] == "above_LOQ"),
        threshold == "at_or_above_LOD" ~ as.integer(.data[[qcol]] %in% c("above_LOD_below_LOQ", "above_LOQ")),
        TRUE ~ NA_integer_
      )
    ) |>
    select(PTB01, exposure, all_of(PRIMARY_COVS)) |>
    drop_na() |>
    mutate(across(where(is.character), as.factor), across(where(is.factor), droplevels))

  if (nrow(d) < 25 || length(unique(d$exposure)) < 2) {
    return(tibble(Polymer = poly, Threshold = threshold, N = nrow(d), Events = sum(d$PTB01 == 1),
                  Exposed = sum(d$exposure == 1), OR = NA_real_, CI_lo = NA_real_, CI_hi = NA_real_,
                  p = NA_real_, se_method = "skipped"))
  }

  fml <- as.formula(paste("PTB01 ~ exposure +", paste(PRIMARY_COVS, collapse = " + ")))
  fit <- glm(fml, data = d, family = binomial(), control = glm.control(maxit = 100, epsilon = 1e-8))
  z <- robust_hc1(fit, "exposure")
  tibble(
    Polymer = poly,
    Threshold = threshold,
    N = nrow(d),
    Events = sum(d$PTB01 == 1),
    Exposed = sum(d$exposure == 1),
    OR = exp(z$estimate),
    CI_lo = exp(z$estimate - 1.96 * z$se),
    CI_hi = exp(z$estimate + 1.96 * z$se),
    p = z$p,
    se_method = z$se_method,
    Covariates = paste(PRIMARY_COVS, collapse = " + ")
  )
}

