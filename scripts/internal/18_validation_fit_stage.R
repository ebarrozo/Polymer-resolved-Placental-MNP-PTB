#!/usr/bin/env Rscript
# INTERNAL FIT STAGE — NOT A MANUSCRIPT-FACING EFFECT SCALE
# -----------------------------------------------------------------------------
# This script is retained to reproduce the original fitted model coefficients and
# analysis samples. Some intermediate columns/labels use the historical fixed
# log10(2) scaling. Do not report those intermediate effect estimates. The
# manuscript-facing scripts in ../ re-express continuous effects on the final
# IQR scale without refitting the models.
# -----------------------------------------------------------------------------
# ============================================================
# 18_placenta_spike_recovery_validation.R
# Placenta spike-recovery, process-loss, matrix-associated attenuation,
# blank-background, and PU/PET PTB QC sensitivity analyses
# ============================================================
#
# Purpose
# -------
# 1) Parse analytical laboratory's paired placenta spike/unspike workbook.
# 2) Parse spike-only, true blank, field blank, and procedural blank controls.
# 3) Estimate whole-process recovery in spike-only controls.
# 4) Estimate paired whole-process recovery in placental matrix.
# 5) Compare placenta recovery with spike-only recovery to quantify
#    matrix-associated attenuation (without claiming a purely instrumental
#    matrix effect, because spikes were added before digestion).
# 6) Characterize blank background, with suspect controls flagged rather than
#    silently excluded.
# 7) Run PU/PET PTB sensitivity analyses based on the existing QC flags,
#    including above-LOQ models using the same primary covariates as script 06.
#
# IMPORTANT DESIGN INTERPRETATION
# -------------------------------
# The polymer standard was added at the START of digestion. Therefore recovery
# reflects the entire workflow (digestion + transfers + spins/washes + analysis).
# Tissue-vs-spike-only differences are called "matrix-associated attenuation of
# whole-process recovery" rather than an isolated instrumental matrix effect.
#
# This script DOES NOT recovery-correct the primary cohort.
# The validation subset is too small and polymer-specific recovery is too
# heterogeneous to justify specimen-level correction of the original cohort.
# ============================================================

