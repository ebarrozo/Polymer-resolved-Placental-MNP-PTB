# ---- C2b. Firth / bias-reduced logistic sensitivity ----
# Prefer logistf when installed; otherwise use brglm2 mean bias reduction.
# If neither package is installed, write an explicit skipped result rather than
# installing packages automatically inside a reproducible manuscript script.
fit_bias_reduced_qc <- function(poly, threshold = c("above_LOQ", "at_or_above_LOD")) {
  threshold <- match.arg(threshold)
  qcol <- paste0("QC_flag_", poly)
  d <- cohort |>
    mutate(
      exposure = case_when(
        threshold == "above_LOQ" ~ as.integer(.data[[qcol]] == "above_LOQ"),
        threshold == "at_or_above_LOD" ~ as.integer(.data[[qcol]] %in% c("above_LOD_below_LOQ", "above_LOQ")),
        TRUE ~ NA_integer_
      )
    ) |>
    select(PTB01, exposure, all_of(PRIMARY_COVS)) |>
    drop_na() |>
    mutate(across(where(is.character), as.factor), across(where(is.factor), droplevels))

  fml <- as.formula(paste("PTB01 ~ exposure +", paste(PRIMARY_COVS, collapse = " + ")))

  if (requireNamespace("logistf", quietly = TRUE)) {
    fit <- try(logistf::logistf(fml, data = d), silent = TRUE)
    if (!inherits(fit, "try-error") && "exposure" %in% names(fit$coefficients)) {
      est <- unname(fit$coefficients["exposure"])
      lo <- unname(fit$ci.lower["exposure"])
      hi <- unname(fit$ci.upper["exposure"])
      pp <- unname(fit$prob["exposure"])
      return(tibble(
        Polymer = poly, Threshold = threshold, Method = "Firth (logistf)",
        N = nrow(d), Events = sum(d$PTB01 == 1), Exposed = sum(d$exposure == 1),
        OR = exp(est), CI_lo = exp(lo), CI_hi = exp(hi), p = pp,
        Covariates = paste(PRIMARY_COVS, collapse = " + ")
      ))
    }
  }

  if (requireNamespace("brglm2", quietly = TRUE)) {
    fit <- try(glm(
      fml, data = d, family = binomial(),
      method = brglm2::brglmFit, type = "AS_mean"
    ), silent = TRUE)
    if (!inherits(fit, "try-error")) {
      sm <- summary(fit)$coefficients
      if ("exposure" %in% rownames(sm)) {
        est <- unname(sm["exposure", "Estimate"])
        se <- unname(sm["exposure", "Std. Error"])
        pp <- unname(sm["exposure", "Pr(>|z|)"])
        return(tibble(
          Polymer = poly, Threshold = threshold, Method = "Bias-reduced logistic (brglm2)",
          N = nrow(d), Events = sum(d$PTB01 == 1), Exposed = sum(d$exposure == 1),
          OR = exp(est), CI_lo = exp(est - 1.96 * se), CI_hi = exp(est + 1.96 * se), p = pp,
          Covariates = paste(PRIMARY_COVS, collapse = " + ")
        ))
      }
    }
  }

  tibble(
    Polymer = poly, Threshold = threshold,
    Method = "SKIPPED: install.packages('logistf') or install.packages('brglm2')",
    N = nrow(d), Events = sum(d$PTB01 == 1), Exposed = sum(d$exposure == 1),
    OR = NA_real_, CI_lo = NA_real_, CI_hi = NA_real_, p = NA_real_,
    Covariates = paste(PRIMARY_COVS, collapse = " + ")
  )
}

