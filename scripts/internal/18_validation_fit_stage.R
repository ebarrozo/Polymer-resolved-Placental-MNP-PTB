# ---- C2c. Leave-one-out adjusted binary threshold models ----
# Primary reviewer-facing LOO analysis is >LOQ. >=LOD is retained as optional
# supporting output because >LOQ is the more stringent analytical-confidence test.
fit_loo_binary_qc <- function(poly, threshold = "above_LOQ") {
  qcol <- paste0("QC_flag_", poly)
  d0 <- cohort |>
    mutate(
      exposure = case_when(
        threshold == "above_LOQ" ~ as.integer(.data[[qcol]] == "above_LOQ"),
        threshold == "at_or_above_LOD" ~ as.integer(.data[[qcol]] %in% c("above_LOD_below_LOQ", "above_LOQ")),
        TRUE ~ NA_integer_
      ),
      row_id_validation = row_number()
    ) |>
    select(row_id_validation, SampleID, PTB01, exposure, all_of(PRIMARY_COVS)) |>
    drop_na() |>
    mutate(across(where(is.character) & !all_of("SampleID"), as.factor), across(where(is.factor), droplevels))

  fml <- as.formula(paste("PTB01 ~ exposure +", paste(PRIMARY_COVS, collapse = " + ")))

  map_dfr(seq_len(nrow(d0)), function(i) {
    d <- d0[-i, , drop = FALSE] |>
      mutate(across(where(is.factor), droplevels))
    fit <- try(suppressWarnings(glm(fml, data = d, family = binomial(), control = glm.control(maxit = 100))), silent = TRUE)
    if (inherits(fit, "try-error") || !"exposure" %in% names(coef(fit)) || !is.finite(coef(fit)["exposure"])) {
      return(tibble(
        Polymer = poly, Threshold = threshold,
        OmittedSample = d0$SampleID[[i]], OR = NA_real_, CI_lo = NA_real_, CI_hi = NA_real_, p = NA_real_
      ))
    }
    sm <- summary(fit)$coefficients
    est <- unname(sm["exposure", "Estimate"])
    se <- unname(sm["exposure", "Std. Error"])
    pp <- unname(sm["exposure", "Pr(>|z|)"])
    tibble(
      Polymer = poly, Threshold = threshold,
      OmittedSample = d0$SampleID[[i]],
      OR = exp(est), CI_lo = exp(est - 1.96 * se), CI_hi = exp(est + 1.96 * se), p = pp
    )
  })
}

