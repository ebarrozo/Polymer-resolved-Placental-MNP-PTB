pick_preferred <- function(paths, preferred_regex, fallback_regex, label) {
  preferred <- paths[str_detect(basename(paths), regex(preferred_regex, ignore_case = TRUE))]
  if (length(preferred) == 1) return(preferred[[1]])
  if (length(preferred) > 1) {
    stop(
      "Found more than one preferred ", label, " workbook: ",
      paste(basename(preferred), collapse = "; "),
      call. = FALSE
    )
  }

  hit <- paths[str_detect(basename(paths), regex(fallback_regex, ignore_case = TRUE))]
  if (length(hit) != 1) {
    stop(
      "Could not uniquely identify the ", label, " workbook in ", SPIKE_DIR,
      ". Candidates: ", paste(basename(hit), collapse = "; "),
      call. = FALSE
    )
  }
  hit[[1]]
}

