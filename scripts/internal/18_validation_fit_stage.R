# ---- C2d. Conservative batch-matched max-blank subtraction sensitivity ----
# We use the batch-matched control MaxBlank_ug that generated the cohort QC thresholds,
# NOT the new 2026 validation blanks. For records representing >1 analytical run,
# MaxBlank_ug is subtracted once per run before dividing by total tissue weight.
# This is deliberately conservative and is used only as a sensitivity analysis.
thresholds_old <- readr::read_csv(IN_THRESH, show_col_types = FALSE)

fit_blank_subtracted_continuous <- function(poly) {
  poly_lc <- tolower(poly)
  mass_col <- paste0("mnp_", poly_lc, "_sum_ug")
  burden_col <- paste0("mnp_", poly_lc, "_ug_g")
  if (!mass_col %in% names(cohort) || !burden_col %in% names(cohort)) {
    stop("Missing expected cohort columns for ", poly, ": ", mass_col, " / ", burden_col)
  }
  max_blank <- thresholds_old |>
    filter(Analyte == poly) |>
    pull(MaxBlank_ug) |>
    first()
  if (!is.finite(max_blank)) stop("No batch-matched MaxBlank_ug found for ", poly)

  d <- cohort |>
    mutate(
      n_runs_for_blank = if_else(is.finite(n_unique_run_id) & n_unique_run_id > 0, as.numeric(n_unique_run_id), 1),
      original_mass_ug = .data[[mass_col]],
      original_burden_ug_g = .data[[burden_col]],
      conservative_blank_mass_ug = max_blank * n_runs_for_blank,
      blank_subtracted_mass_ug = pmax(original_mass_ug - conservative_blank_mass_ug, 0),
      blank_subtracted_ug_g = if_else(total_tissue_weight_g > 0, blank_subtracted_mass_ug / total_tissue_weight_g, NA_real_),
      x_original = log2(original_burden_ug_g + 1),
      x_blank_subtracted = log2(blank_subtracted_ug_g + 1)
    ) |>
    select(SampleID, PTB01, all_of(PRIMARY_COVS), n_runs_for_blank,
           original_mass_ug, original_burden_ug_g, conservative_blank_mass_ug,
           blank_subtracted_mass_ug, blank_subtracted_ug_g, x_original, x_blank_subtracted) |>
    drop_na(PTB01, all_of(PRIMARY_COVS)) |>
    mutate(across(where(is.character) & !all_of("SampleID"), as.factor), across(where(is.factor), droplevels))

  fit_one <- function(xvar, label) {
    dd <- d |> filter(is.finite(.data[[xvar]]))
    fml <- as.formula(paste("PTB01 ~", xvar, "+", paste(PRIMARY_COVS, collapse = " + ")))
    fit <- glm(fml, data = dd, family = binomial(), control = glm.control(maxit = 100, epsilon = 1e-8))
    z <- robust_hc1(fit, xvar)
    tibble(
      Polymer = poly,
      Sensitivity = label,
      BatchMatched_MaxBlank_ug_per_run = max_blank,
      N = nrow(dd), Events = sum(dd$PTB01 == 1),
      OR_per_doubling_plus1 = exp(z$estimate),
      CI_lo = exp(z$estimate - 1.96 * z$se),
      CI_hi = exp(z$estimate + 1.96 * z$se),
      p = z$p,
      se_method = z$se_method,
      n_zero_after_subtraction = if (label == "MaxBlank_subtracted_per_run") sum(dd$blank_subtracted_ug_g == 0, na.rm = TRUE) else NA_integer_,
      Covariates = paste(PRIMARY_COVS, collapse = " + ")
    )
  }

  list(
    models = bind_rows(
      fit_one("x_original", "Original_recomputed_from_analysis_ready_table"),
      fit_one("x_blank_subtracted", "MaxBlank_subtracted_per_run")
    ),
    specimen_audit = d |>
      transmute(
        Polymer = poly, SampleID, PTB01, n_runs_for_blank,
        BatchMatched_MaxBlank_ug_per_run = max_blank,
        original_mass_ug, conservative_blank_mass_ug, blank_subtracted_mass_ug,
        original_burden_ug_g, blank_subtracted_ug_g
      )
  )
}

