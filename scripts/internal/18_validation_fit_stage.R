# ---- C2a. Explicit 2x2 term/PTB tables for analytical thresholds ----
make_2x2_qc <- function(poly, threshold = c("above_LOQ", "at_or_above_LOD")) {
  threshold <- match.arg(threshold)
  qcol <- paste0("QC_flag_", poly)
  d <- cohort |>
    transmute(
      PTB = factor(if_else(PTB01 == 1, "Preterm", "Term"), levels = c("Term", "Preterm")),
      Exposure = case_when(
        threshold == "above_LOQ" ~ if_else(.data[[qcol]] == "above_LOQ", "Exposed", "Not_exposed"),
        threshold == "at_or_above_LOD" ~ if_else(.data[[qcol]] %in% c("above_LOD_below_LOQ", "above_LOQ"), "Exposed", "Not_exposed"),
        TRUE ~ NA_character_
      )
    ) |>
    drop_na() |>
    mutate(Exposure = factor(Exposure, levels = c("Not_exposed", "Exposed")))

  tab <- table(d$PTB, d$Exposure)
  ft <- try(stats::fisher.test(tab), silent = TRUE)
  crude_or <- ci_lo <- ci_hi <- p_fisher <- NA_real_
  if (!inherits(ft, "try-error")) {
    crude_or <- unname(ft$estimate)
    ci_lo <- unname(ft$conf.int[1])
    ci_hi <- unname(ft$conf.int[2])
    p_fisher <- ft$p.value
  }

  counts <- as.data.frame(tab) |>
    as_tibble() |>
    rename(Delivery = Var1, Exposure = Var2, n = Freq) |>
    mutate(Polymer = poly, Threshold = threshold, .before = 1)

  stats <- tibble(
    Polymer = poly,
    Threshold = threshold,
    N = nrow(d),
    Term_exposed = unname(tab["Term", "Exposed"]),
    Term_not_exposed = unname(tab["Term", "Not_exposed"]),
    Preterm_exposed = unname(tab["Preterm", "Exposed"]),
    Preterm_not_exposed = unname(tab["Preterm", "Not_exposed"]),
    Crude_OR_Fisher = crude_or,
    Crude_CI_lo = ci_lo,
    Crude_CI_hi = ci_hi,
    Fisher_p = p_fisher
  )
  list(counts = counts, stats = stats)
}

