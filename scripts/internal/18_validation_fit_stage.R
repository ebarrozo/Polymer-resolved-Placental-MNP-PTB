parse_marcus_num <- function(x, nd_as_zero = FALSE) {
  x_chr <- str_squish(as.character(x))
  is_nd <- is.na(x_chr) | x_chr == "" | x_chr %in% c("---", "--", "ND", "N/D", "NA")
  out <- suppressWarnings(parse_number(x_chr))
  if (nd_as_zero) out[is_nd] <- 0
  out
}

sanitize_sample <- function(x) str_squish(as.character(x))
strip_spike_suffix <- function(x) str_remove(sanitize_sample(x), "\\s+S$")

robust_hc1 <- function(fit, term) {
  if (requireNamespace("sandwich", quietly = TRUE) && requireNamespace("lmtest", quietly = TRUE)) {
    ct <- try(
      suppressWarnings(lmtest::coeftest(fit, vcov. = sandwich::vcovHC(fit, type = "HC1"))),
      silent = TRUE
    )
    if (!inherits(ct, "try-error") && term %in% rownames(ct)) {
      return(tibble(
        estimate = unname(ct[term, "Estimate"]),
        se = unname(ct[term, "Std. Error"]),
        p = 2 * pnorm(abs(unname(ct[term, "Estimate"]) / unname(ct[term, "Std. Error"])), lower.tail = FALSE),
        se_method = "HC1"
      ))
    }
  }
  sm <- summary(fit)$coefficients
  if (!term %in% rownames(sm)) return(tibble(estimate = NA_real_, se = NA_real_, p = NA_real_, se_method = "missing"))
  tibble(
    estimate = unname(sm[term, "Estimate"]),
    se = unname(sm[term, "Std. Error"]),
    p = unname(sm[term, "Pr(>|z|)"]),
    se_method = "model_based"
  )
}

usable_covariates <- function(dat, covs) {
  keep <- character()
  for (cv in covs) {
    if (!cv %in% names(dat)) next
    x <- dat[[cv]]
    x_nonmiss <- x[!is.na(x)]
    if (!length(x_nonmiss)) next
    if (is.numeric(x_nonmiss) || is.integer(x_nonmiss)) {
      if (length(unique(x_nonmiss)) < 2) next
    } else {
      if (length(unique(as.character(x_nonmiss))) < 2) next
    }
    keep <- c(keep, cv)
  }
  keep
}

# ============================================================
# PART A. Parse paired placenta spike/unspike workbook
# ============================================================
spike_sheet <- readxl::read_excel(IN_TISSUE_SPIKE, sheet = "Data Analysis", col_names = FALSE)

# Polymer result table: first row = sample IDs; first column rows 2:13 = polymers.
sample_headers <- spike_sheet[1, -1] |> unlist(use.names = FALSE) |> as.character() |> str_squish()
poly_rows <- which(as.character(spike_sheet[[1]]) %in% POLYS)
if (length(poly_rows) < length(POLYS)) stop("Could not identify all 12 polymer rows in tissue workbook.")
poly_rows <- poly_rows[match(POLYS, as.character(spike_sheet[[1]][poly_rows]))]

# Placenta sample columns are before FF and are identified by TPL in the header.
plac_cols_rel <- which(str_detect(sample_headers, regex("TPL", ignore_case = TRUE)))
plac_cols <- plac_cols_rel + 1L
plac_headers <- sample_headers[plac_cols_rel]

plac_long <- map_dfr(seq_along(plac_cols), function(k) {
  cc <- plac_cols[[k]]
  sid <- plac_headers[[k]]
  tibble(
    SampleID_validation = sid,
    BaseSampleID = strip_spike_suffix(sid),
    SpikeStatus = if_else(str_detect(sid, "\\s+S$"), "Spiked", "Unspiked"),
    Polymer = POLYS,
    reported_raw = as.character(spike_sheet[[cc]][poly_rows]),
    observed_ug = parse_marcus_num(spike_sheet[[cc]][poly_rows], nd_as_zero = FALSE),
    observed_ug_nd0 = parse_marcus_num(spike_sheet[[cc]][poly_rows], nd_as_zero = TRUE),
    reported_nd = is.na(observed_ug)
  )
})

# Locate expected-addition block dynamically.
expected_cell <- which(spike_sheet == "Expected", arr.ind = TRUE)
spiked_mass_cell <- which(spike_sheet == "Spiked: (mg)", arr.ind = TRUE)
if (nrow(expected_cell) != 1 || nrow(spiked_mass_cell) != 1) {
  stop("Could not uniquely locate Expected and Spiked: (mg) cells in tissue workbook.")
}

exp_header_row <- expected_cell[1, "row"]
exp_start_col <- expected_cell[1, "col"] + 1L
exp_polys <- spike_sheet[exp_header_row, exp_start_col:(exp_start_col + 11L)] |> unlist(use.names = FALSE) |> as.character()
if (!setequal(exp_polys, PLOT_POLYS)) {
  warning("Expected-addition polymer header differs from anticipated 12 polymers: ", paste(exp_polys, collapse = ", "))
}

spike_mass_col <- spiked_mass_cell[1, "col"]
meta_start_row <- spiked_mass_cell[1, "row"] + 1L
meta_rows <- meta_start_row:nrow(spike_sheet)

meta_tbl <- tibble(
  row = meta_rows,
  SampleID_validation = sanitize_sample(spike_sheet[[1]][meta_rows]),
  spike_mass_mg = parse_marcus_num(spike_sheet[[spike_mass_col]][meta_rows])
) |>
  filter(SampleID_validation %in% plac_headers, str_detect(SampleID_validation, "\\s+S$"))

expected_matrix <- map_dfr(seq_len(nrow(meta_tbl)), function(i) {
  rr <- meta_tbl$row[[i]]
  tibble(
    SampleID_validation = meta_tbl$SampleID_validation[[i]],
    spike_mass_mg = meta_tbl$spike_mass_mg[[i]],
    Polymer = exp_polys,
    expected_as_entered_ug = parse_marcus_num(unlist(spike_sheet[rr, exp_start_col:(exp_start_col + 11L)]), nd_as_zero = FALSE)
  )
})

# Derive standard composition from internally consistent COMPLETE placenta rows.
# This intentionally avoids trusting any single row; the 28978 row in the supplied
# workbook is retained for audit but may contain shifted expected-value cells.
coef_by_row <- expected_matrix |>
  filter(is.finite(spike_mass_mg), spike_mass_mg > 0) |>
  group_by(SampleID_validation) |>
  mutate(n_expected_present = sum(is.finite(expected_as_entered_ug))) |>
  ungroup() |>
  filter(n_expected_present == 12) |>
  mutate(expected_ug_per_mg_standard = expected_as_entered_ug / spike_mass_mg)

standard_composition <- coef_by_row |>
  group_by(Polymer) |>
  summarise(
    n_rows = n(),
    expected_ug_per_mg_standard = median(expected_ug_per_mg_standard, na.rm = TRUE),
    min_ug_per_mg = min(expected_ug_per_mg_standard, na.rm = TRUE),
    max_ug_per_mg = max(expected_ug_per_mg_standard, na.rm = TRUE),
    cv_pct = 100 * sd(expected_ug_per_mg_standard, na.rm = TRUE) / mean(expected_ug_per_mg_standard, na.rm = TRUE),
    .groups = "drop"
  ) |>
  arrange(match(Polymer, PLOT_POLYS))

if (nrow(standard_composition) != 12 || any(!is.finite(standard_composition$expected_ug_per_mg_standard))) {
  stop("Could not derive all 12 polymer standard-composition coefficients from tissue workbook.")
}

# Recompute expected polymer additions consistently from spike mass and derived composition.
expected_recomputed <- meta_tbl |>
  select(SampleID_validation, spike_mass_mg) |>
  crossing(standard_composition |> select(Polymer, expected_ug_per_mg_standard)) |>
  mutate(expected_spike_ug = spike_mass_mg * expected_ug_per_mg_standard)

# Audit workbook-entered vs recomputed expected amounts.
expected_audit <- expected_matrix |>
  left_join(expected_recomputed, by = c("SampleID_validation", "spike_mass_mg", "Polymer")) |>
  mutate(
    expected_diff_ug = expected_as_entered_ug - expected_spike_ug,
    expected_diff_pct = 100 * expected_diff_ug / expected_spike_ug,
    expected_cell_mismatch = is.finite(expected_as_entered_ug) & abs(expected_diff_pct) > 2
  )

# Pair spiked with unspiked aliquots.
plac_spiked <- plac_long |>
  filter(SpikeStatus == "Spiked") |>
  select(BaseSampleID, SampleID_spiked = SampleID_validation, Polymer,
         spiked_observed_ug = observed_ug,
         spiked_observed_ug_nd0 = observed_ug_nd0,
         spiked_reported_nd = reported_nd)

plac_unspiked <- plac_long |>
  filter(SpikeStatus == "Unspiked") |>
  select(BaseSampleID, SampleID_unspiked = SampleID_validation, Polymer,
         unspiked_observed_ug = observed_ug,
         unspiked_observed_ug_nd0 = observed_ug_nd0,
         unspiked_reported_nd = reported_nd)

placenta_recovery <- plac_spiked |>
  left_join(plac_unspiked, by = c("BaseSampleID", "Polymer")) |>
  left_join(
    expected_recomputed |>
      mutate(BaseSampleID = strip_spike_suffix(SampleID_validation)) |>
      select(BaseSampleID, Polymer, spike_mass_mg, expected_spike_ug),
    by = c("BaseSampleID", "Polymer")
  ) |>
  mutate(
    paired_unspiked_available = !is.na(SampleID_unspiked),
    delta_observed_ug_nd0 = if_else(
      paired_unspiked_available,
      spiked_observed_ug_nd0 - unspiked_observed_ug_nd0,
      NA_real_
    ),
    apparent_recovery_pct = 100 * delta_observed_ug_nd0 / expected_spike_ug,
    apparent_recovery_fraction = apparent_recovery_pct / 100,
    recovery_negative = apparent_recovery_pct < 0,
    recovery_gt_150 = apparent_recovery_pct > 150
  )

placenta_recovery_summary <- placenta_recovery |>
  filter(paired_unspiked_available) |>
  group_by(Polymer) |>
  summarise(
    n_pairs = n(),
    median_recovery_pct = median(apparent_recovery_pct, na.rm = TRUE),
    mean_recovery_pct = mean(apparent_recovery_pct, na.rm = TRUE),
    min_recovery_pct = min(apparent_recovery_pct, na.rm = TRUE),
    max_recovery_pct = max(apparent_recovery_pct, na.rm = TRUE),
    q25_recovery_pct = quantile(apparent_recovery_pct, 0.25, na.rm = TRUE),
    q75_recovery_pct = quantile(apparent_recovery_pct, 0.75, na.rm = TRUE),
    .groups = "drop"
  ) |>
  arrange(match(Polymer, PLOT_POLYS))

placenta_overall_recovery <- placenta_recovery |>
  filter(paired_unspiked_available) |>
  group_by(BaseSampleID, spike_mass_mg) |>
  summarise(
    expected_total_ug = sum(expected_spike_ug, na.rm = TRUE),
    delta_total_observed_ug = sum(delta_observed_ug_nd0, na.rm = TRUE),
    overall_apparent_recovery_pct = 100 * delta_total_observed_ug / expected_total_ug,
    .groups = "drop"
  )

# ============================================================
# PART B. Parse new true/field/procedural blanks and spike-only controls
# ============================================================
ctrl_raw <- readxl::read_excel(IN_CONTROLS_NEW, sheet = 1, col_names = FALSE)

# A block header is any row whose NEXT row begins with "Polymer".
block_header_rows <- which(
  seq_len(nrow(ctrl_raw) - 1L) |> map_lgl(~ str_squish(as.character(ctrl_raw[[1]][.x + 1L])) == "Polymer")
)
if (!length(block_header_rows)) stop("No control blocks detected in control workbook.")

block_labels <- sanitize_sample(ctrl_raw[[1]][block_header_rows])
block_id <- character(length(block_header_rows))
current_block <- 0L
for (i in seq_along(block_header_rows)) {
  if (tolower(block_labels[[i]]) == "true blank") current_block <- current_block + 1L
  block_id[[i]] <- LETTERS[current_block]
}

controls_long <- map_dfr(seq_along(block_header_rows), function(i) {
  h <- block_header_rows[[i]]
  label <- block_labels[[i]]
  bid <- block_id[[i]]
  rr <- (h + 2L):min(h + 14L, nrow(ctrl_raw))
  tmp <- tibble(
    Polymer = sanitize_sample(ctrl_raw[[1]][rr]),
    reported_raw = as.character(ctrl_raw[[3]][rr]),
    observed_ug = parse_marcus_num(ctrl_raw[[3]][rr], nd_as_zero = FALSE),
    observed_ug_nd0 = parse_marcus_num(ctrl_raw[[3]][rr], nd_as_zero = TRUE)
  ) |>
    filter(Polymer %in% POLYS)

  control_type <- case_when(
    str_detect(tolower(label), "^spike") ~ "spike_only",
    tolower(label) == "true blank" ~ "true_blank",
    tolower(label) == "field blank" ~ "field_blank",
    str_detect(tolower(label), "^blank\\s*[0-9]+") ~ "procedural_blank",
    TRUE ~ "other"
  )

  spike_mass <- if (control_type == "spike_only") parse_number(label) else NA_real_

  tmp |>
    mutate(
      ControlBlock = bid,
      MatrixLabel = unname(CONTROL_BLOCK_MATRIX[bid]),
      ControlLabel = label,
      ControlType = control_type,
      spike_mass_mg = spike_mass,
      reported_nd = is.na(observed_ug),
      .before = 1
    )
})

# Apply confirmed control provenance.
# Block B "blank 3" was confirmed by the analytical laboratory to be a
# spiked sample with unknown spike mass rather than a procedural blank.
controls_long <- controls_long |>
  mutate(
    confirmed_mislabeled_spike =
      ControlBlock == KNOWN_MISLABELED_SPIKE_BLOCK &
      str_to_lower(str_squish(ControlLabel)) == KNOWN_MISLABELED_SPIKE_LABEL,
    ControlType_original = ControlType,
    ControlType = if_else(
      confirmed_mislabeled_spike,
      "misclassified_spike_unknown_mass",
      ControlType
    ),
    exclude_from_blank_analysis = confirmed_mislabeled_spike
  )

# Control-level totals are retained for audit. Statistical high-blank flags
# are calculated only among actual blank controls. The confirmed mislabeled
# spike is excluded by identity, not by an outlier rule.
control_totals <- controls_long |>
  group_by(
    ControlBlock, MatrixLabel, ControlLabel,
    ControlType_original, ControlType,
    confirmed_mislabeled_spike, exclude_from_blank_analysis
  ) |>
  summarise(
    total_observed_ug_nd0 = sum(observed_ug_nd0, na.rm = TRUE),
    .groups = "drop"
  )

blank_totals_only <- control_totals |>
  filter(
    ControlType %in% c("true_blank", "field_blank", "procedural_blank"),
    !exclude_from_blank_analysis
  )

med_blank_total <- median(blank_totals_only$total_observed_ug_nd0, na.rm = TRUE)
mad_blank_total <- mad(
  blank_totals_only$total_observed_ug_nd0,
  constant = 1.4826,
  na.rm = TRUE
)
if (!is.finite(mad_blank_total) || mad_blank_total == 0) mad_blank_total <- 1e-9

control_totals <- control_totals |>
  mutate(
    suspect_high_blank =
      ControlType %in% c("true_blank", "field_blank", "procedural_blank") &
      !exclude_from_blank_analysis &
      total_observed_ug_nd0 > med_blank_total + 8 * mad_blank_total,
    exclusion_reason = case_when(
      confirmed_mislabeled_spike ~
        "Confirmed by analytical laboratory as spiked sample with unknown spike amount; not a blank",
      TRUE ~ NA_character_
    )
  )

controls_long <- controls_long |>
  left_join(
    control_totals |>
      select(
        ControlBlock, ControlLabel,
        suspect_high_blank, exclusion_reason
      ),
    by = c("ControlBlock", "ControlLabel")
  )

# Spike-only process recovery.
# Recovery can only be calculated for controls explicitly labeled as spike-only
# with a known spike mass. The confirmed B blank 3 misclassification has an
# unknown spike amount and is therefore not used for recovery estimation.
spike_only_recovery <- controls_long |>
  filter(ControlType == "spike_only") |>
  left_join(
    standard_composition |>
      select(Polymer, expected_ug_per_mg_standard),
    by = "Polymer"
  ) |>
  mutate(
    expected_spike_ug = spike_mass_mg * expected_ug_per_mg_standard,
    process_recovery_pct = 100 * observed_ug_nd0 / expected_spike_ug,
    process_recovery_fraction = process_recovery_pct / 100
  )

# Retain a pooled A+B summary for audit only.
spike_only_summary_pooled <- spike_only_recovery |>
  group_by(Polymer) |>
  summarise(
    n_spike_only = n(),
    median_process_recovery_pct = median(process_recovery_pct, na.rm = TRUE),
    mean_process_recovery_pct = mean(process_recovery_pct, na.rm = TRUE),
    min_process_recovery_pct = min(process_recovery_pct, na.rm = TRUE),
    max_process_recovery_pct = max(process_recovery_pct, na.rm = TRUE),
    q25_process_recovery_pct = quantile(process_recovery_pct, 0.25, na.rm = TRUE),
    q75_process_recovery_pct = quantile(process_recovery_pct, 0.75, na.rm = TRUE),
    .groups = "drop"
  )

spike_only_summary_by_block <- spike_only_recovery |>
  group_by(ControlBlock, MatrixLabel, Polymer) |>
  summarise(
    n_spike_only = n(),
    median_process_recovery_pct = median(process_recovery_pct, na.rm = TRUE),
    mean_process_recovery_pct = mean(process_recovery_pct, na.rm = TRUE),
    min_process_recovery_pct = min(process_recovery_pct, na.rm = TRUE),
    max_process_recovery_pct = max(process_recovery_pct, na.rm = TRUE),
    q25_process_recovery_pct = quantile(process_recovery_pct, 0.25, na.rm = TRUE),
    q75_process_recovery_pct = quantile(process_recovery_pct, 0.75, na.rm = TRUE),
    .groups = "drop"
  )

